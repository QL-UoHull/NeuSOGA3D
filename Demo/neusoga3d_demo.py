def process_contour_hybrid(c, x_min, x_max, y_min, y_max, img_size):
    coarse_x = gaussian_filter(c[:, 0].astype(float), sigma=6.0, mode='wrap')
    coarse_y = gaussian_filter(c[:, 1].astype(float), sigma=6.0, mode='wrap')
    curve_coarse = np.column_stack((coarse_x, coarse_y))
    fine_x = gaussian_filter(c[:, 0].astype(float), sigma=1.5, mode='wrap')
    fine_y = gaussian_filter(c[:, 1].astype(float), sigma=1.5, mode='wrap')
    curve_fine = np.column_stack((fine_x, fine_y))

    deviation = np.linalg.norm(curve_coarse - curve_fine, axis=1)
    missed_mask = (deviation > 2.0).astype(float)
    blend_weight = gaussian_filter(missed_mask, sigma=3.0, mode='wrap')
    blend_weight = np.clip(blend_weight, 0, 1).reshape(-1, 1)

    hybrid_curve = curve_coarse * (1.0 - blend_weight) + curve_fine * blend_weight
    sampled = approximate_polygon(hybrid_curve, tolerance=0.8)

    if len(sampled) < 3: return np.empty((0, 2))
    if np.linalg.norm(sampled[0] - sampled[-1]) < 1e-5: sampled = sampled[:-1]
    if len(sampled) < 3: return np.empty((0, 2))

    x_coords = x_min + (sampled[:, 0] / (img_size - 1)) * (x_max - x_min)
    y_coords = y_min + ((img_size - 1 - sampled[:, 1]) / (img_size - 1)) * (y_max - y_min)
    poly = np.column_stack((x_coords, y_coords))

    x_pts, y_pts = poly[:, 0], poly[:, 1]
    signed_area = np.sum(x_pts[:-1] * y_pts[1:] - x_pts[1:] * y_pts[:-1]) + (x_pts[-1] * y_pts[0] - x_pts[0] * y_pts[-1])
    if signed_area < 0: poly = poly[::-1]
    return poly

def holistic_hybrid_extraction(pc_2d, predictor, img_size=512, margin=0.15):
    # [CRITICAL FIX]: Force Aspect Ratio Preservation
    # Prevents SAM from stretching the side/front view into an unrecognizable square
    x_min, x_max = pc_2d[:, 0].min() - margin, pc_2d[:, 0].max() + margin
    y_min, y_max = pc_2d[:, 1].min() - margin, pc_2d[:, 1].max() + margin
    max_range = max(x_max - x_min, y_max - y_min)

    x_center = (x_max + x_min) / 2.0
    y_center = (y_max + y_min) / 2.0

    x_min, x_max = x_center - max_range / 2.0, x_center + max_range / 2.0
    y_min, y_max = y_center - max_range / 2.0, y_center + max_range / 2.0

    img_gray = np.zeros((img_size, img_size), dtype=np.uint8)
    for p in pc_2d:
        px = int(((p[0] - x_min) / (x_max - x_min)) * (img_size - 1))
        py = int(((p[1] - y_min) / (y_max - y_min)) * (img_size - 1))
        cv2.circle(img_gray, (px, py), radius=5, color=255, thickness=-1)

    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (11, 11))
    mask_solid = cv2.morphologyEx(img_gray, cv2.MORPH_CLOSE, kernel)
    mask_flipped = cv2.flip(mask_solid, 0)
    predictor.set_image(cv2.cvtColor(mask_flipped, cv2.COLOR_GRAY2RGB))

    dist_transform = cv2.distanceTransform(mask_flipped, cv2.DIST_L2, 5)
    local_max_coords = peak_local_max(dist_transform, min_distance=8, threshold_abs=0.05 * dist_transform.max())

    if len(local_max_coords) == 0:
        _, _, _, max_loc = cv2.minMaxLoc(dist_transform)
        prompts = np.array([[max_loc[0], max_loc[1]]])
    else: prompts = np.array([[c[1], c[0]] for c in local_max_coords])

    masks, _, _ = predictor.predict(point_coords=prompts, point_labels=np.ones(len(prompts)), multimask_output=False)
    features = []

    if len(masks) > 0:
        mask_binary = (masks[0] * 255).astype(np.uint8)
        if mask_binary[0, 0] > 128 and mask_binary[img_size-1, img_size-1] > 128:
            mask_binary = cv2.bitwise_not(mask_binary)

        contours, _ = cv2.findContours(mask_binary, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        for idx, c in enumerate(contours):
            if cv2.contourArea(c) < 5: continue
            c = c.reshape(-1, 2)
            c = c[np.insert(np.sum(np.abs(np.diff(c, axis=0)), axis=1) > 0, 0, True)]
            if len(c) >= 10:
                poly = process_contour_hybrid(c, x_min, x_max, y_min, y_max, img_size)
                if len(poly) > 0: features.append({'polygon': poly})

    if len(features) == 0:
        contours, _ = cv2.findContours(mask_flipped, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        for idx, c in enumerate(contours):
            if cv2.contourArea(c) < 5: continue
            c = c.reshape(-1, 2)
            if len(c) >= 3:
                poly = process_contour_hybrid(c, x_min, x_max, y_min, y_max, img_size)
                if len(poly) > 0: features.append({'polygon': poly})

    return features

def generate_sam_implicit_field_2d(pc_2d, predictor, grid_size, bounds):
    xx, yy = np.meshgrid(np.linspace(bounds[0], bounds[1], grid_size),
                         np.linspace(bounds[0], bounds[1], grid_size), indexing='ij')
    full_field = np.zeros((grid_size, grid_size), dtype=np.float64)
    if len(pc_2d) < 5: return full_field

    features = holistic_hybrid_extraction(pc_2d, predictor, img_size=512)
    for feature in features:
        spline = np.abs(ImpSpline2D(xx, yy, feature['polygon'], delta=0.015, n=2))
        full_field += spline
    return np.clip(full_field, 0.0, 1.0)

def generate_solid_area_slice(pts_2d, grid_size, bounds):
    if len(pts_2d) < 3: return np.zeros((grid_size, grid_size), dtype=np.float64)

    img_size = 512
    binary_canvas = np.zeros((img_size, img_size), dtype=np.uint8)

    x_coords = ((pts_2d[:, 0] - bounds[0]) / (bounds[1] - bounds[0]) * (img_size - 1)).astype(int)
    y_coords = ((pts_2d[:, 1] - bounds[0]) / (bounds[1] - bounds[0]) * (img_size - 1)).astype(int)
    x_coords = np.clip(x_coords, 0, img_size - 1)
    y_coords = np.clip(y_coords, 0, img_size - 1)

    for x, y in zip(x_coords, y_coords):
        cv2.circle(binary_canvas, (x, y), radius=6, color=255, thickness=-1)

    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (15, 15))
    closed = cv2.morphologyEx(binary_canvas, cv2.MORPH_CLOSE, kernel)

    kernel_dilate = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (5, 5))
    dilated = cv2.dilate(closed, kernel_dilate)

    solid_mask = ndi.binary_fill_holes(dilated > 0).astype(np.uint8) * 255
    contours, _ = cv2.findContours(solid_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    xx, yy = np.meshgrid(np.linspace(bounds[0], bounds[1], grid_size),
                         np.linspace(bounds[0], bounds[1], grid_size), indexing='ij')
    F_total = np.zeros((grid_size, grid_size), dtype=np.float64)
    has_valid = False

    for contour in contours:
        if cv2.contourArea(contour) < 1.0: continue
        poly = cv2.approxPolyDP(contour, epsilon=0.8, closed=True)

        if len(poly) >= 3:
            poly_data = poly.reshape(-1, 2).astype(np.float64)
            poly_physical = bounds[0] + (poly_data / (img_size - 1)) * (bounds[1] - bounds[0])
            F_poly = np.abs(ImpSpline2D(xx, yy, poly_physical, delta=0.04, n=2))
            F_total = np.maximum(F_total, np.clip(F_poly, 0.0, 1.0))
            has_valid = True

    if not has_valid: return np.zeros((grid_size, grid_size), dtype=np.float64)
    return F_total

