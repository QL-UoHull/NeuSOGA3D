def build_explicit_psps_loft(voxel_pts, slice_axis, grid_size, num_slices, bounds):
    perp_axes = [i for i in [0, 1, 2] if i != slice_axis]
    pos_min, pos_max = np.min(voxel_pts[:, slice_axis]), np.max(voxel_pts[:, slice_axis])

    base_positions = np.linspace(pos_min, pos_max, num_slices)
    step = (pos_max - pos_min) / max(num_slices - 1, 1)
    half_window = 1.8 * step

    slice_fields = []
    slice_fields.append(np.zeros((grid_size, grid_size), dtype=np.float64))

    for center in base_positions:
        mask = (voxel_pts[:, slice_axis] >= center - half_window) & (voxel_pts[:, slice_axis] <= center + half_window)
        pts_in_slice = voxel_pts[mask]
        slice_fields.append(generate_solid_area_slice(pts_in_slice[:, perp_axes], grid_size, bounds))

    slice_fields.append(np.zeros((grid_size, grid_size), dtype=np.float64))
    slice_positions = np.concatenate(([pos_min - step], base_positions, [pos_max + step]))
    total_slices = len(slice_positions)

    F_cyl = np.zeros((grid_size, grid_size, grid_size), dtype=np.float64)
    axis_coords = np.linspace(bounds[0], bounds[1], grid_size)

    for i_coord in range(grid_size):
        val = axis_coords[i_coord]
        F_val = np.zeros((grid_size, grid_size), dtype=np.float64)
        for i in range(total_slices):
            B_i = evaluate_PSPS_basis(val, slice_positions, i, 2, transition_delta=1.0)
            if B_i > 0: F_val += B_i * slice_fields[i]

        if slice_axis == 0: F_cyl[i_coord, :, :] = F_val
        elif slice_axis == 1: F_cyl[:, i_coord, :] = F_val
        else: F_cyl[:, :, i_coord] = F_val

    return F_cyl

def run_pure_implicit_reconstruction(pc_3d, predictor, grid_size=110, num_slices=36, blend_eps=0.03):
    bounds = (-1.3, 1.3)

    print("  -> Evaluating Orthographic Constraints (For Plotting)...")
    F_top_2d   = generate_sam_implicit_field_2d(pc_3d[:, [0, 1]], predictor, grid_size, bounds)
    F_front_2d = generate_sam_implicit_field_2d(pc_3d[:, [0, 2]], predictor, grid_size, bounds)
    F_side_2d  = generate_sam_implicit_field_2d(pc_3d[:, [1, 2]], predictor, grid_size, bounds)

    print("  -> Computing F_x(x,y,z) = Sum[ S_i(y,z) B_i(x) ]...")
    F_x = build_explicit_psps_loft(pc_3d, 0, grid_size, num_slices, bounds)

    print("  -> Computing F_y(x,y,z) = Sum[ S_i(x,z) B_i(y) ]...")
    F_y = build_explicit_psps_loft(pc_3d, 1, grid_size, num_slices, bounds)

    print("  -> Computing F_z(x,y,z) = Sum[ S_i(x,y) B_i(z) ]...")
    F_z = build_explicit_psps_loft(pc_3d, 2, grid_size, num_slices, bounds)

    print("  -> Fusing Implicit Volumes: F_final = F_x ∩ F_y ∩ F_z...")
    F_final = apply_softMin2_3D(F_x, F_y, eps=blend_eps)
    F_final = apply_softMin2_3D(F_final, F_z, eps=blend_eps)

    return F_final, F_x, F_y, F_z, (F_top_2d, F_front_2d, F_side_2d)

