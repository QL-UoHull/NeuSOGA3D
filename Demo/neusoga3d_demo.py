def get_phong_facecolors(vertices, faces, color_hex, elev, azim):
    h = color_hex.lstrip('#')
    base_color = np.array([int(h[i:i+2], 16) / 255.0 for i in (0, 2, 4)])

    view_dir = np.array([
        math.cos(math.radians(elev)) * math.cos(math.radians(azim)),
        math.cos(math.radians(elev)) * math.sin(math.radians(azim)),
        math.sin(math.radians(elev))
    ])

    light_elev = elev + 40
    light_azim = azim - 30
    light_dir = np.array([
        math.cos(math.radians(light_elev)) * math.cos(math.radians(light_azim)),
        math.cos(math.radians(light_elev)) * math.sin(math.radians(light_azim)),
        math.sin(math.radians(light_elev))
    ])

    v0, v1, v2 = vertices[faces[:, 0]], vertices[faces[:, 1]], vertices[faces[:, 2]]
    normals = np.cross(v1 - v0, v2 - v0)
    norms = np.linalg.norm(normals, axis=1, keepdims=True)
    norms[norms == 0] = 1e-5
    normals = normals / norms

    dot_view = np.sum(normals * view_dir, axis=1)
    normals[dot_view < 0] *= -1

    diffuse = np.clip(np.sum(normals * light_dir, axis=1), 0, 1)

    half_vec = light_dir + view_dir
    half_vec = half_vec / np.linalg.norm(half_vec)
    spec_dot = np.clip(np.sum(normals * half_vec, axis=1), 0, 1)
    specular = np.power(spec_dot, 25.0)

    ambient = 0.45
    intensity = ambient + 0.65 * diffuse

    colors = np.zeros((len(faces), 4))
    for i in range(3):
        colors[:, i] = np.clip(base_color[i] * intensity + 0.55 * specular, 0, 1)
    colors[:, 3] = 1.0
    return colors


